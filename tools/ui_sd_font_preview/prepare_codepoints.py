"""Generate codepoints only; UI glyph pixels are read from SD at runtime."""
from pathlib import Path
import argparse
import re

root = Path(__file__).resolve().parents[2]
target = root / 'src/services/UiFontCodepoints.h'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

# The timer page is in src/ now, so the normal string scan covers its literals.
# Keep this list so the already-shipped font-14.ui.bin subset (whose codepoint
# set was generated with these entries) stays byte-for-byte valid and does not
# need a server re-upload. 闹 is retained because the alarm menu slot was
# repurposed as the timer; dropping it would change kCount and invalidate the
# shipped subset's expectedCount.
RESERVED_UI_LITERALS = (
    '定时器', '选择时长，OK 立即开始', 'OK 进入自定义时长', '自定义',
    '1分钟', '5分钟', '10分钟', '15分钟', '30分钟', '60分钟',
    'OK 开始', 'OK 进入', 'Right 切换步进', '增加', '减少',
    'OK 暂停', 'OK 继续', '计时中', '已暂停', '剩余', '共',
    'OK 停止', '放弃当前计时？', '取消', '时间到', '任意按键停止',
    '定时剩余', '时长', '切换', '步进', '按键', '进入', '开始',
    '暂停', '继续', '返回', '当前', '计时', '时间', '选择', '立即', '分钟',
    '闹钟', '操作',
)

points = set(range(32, 127))
points.update(ord(c) for text in RESERVED_UI_LITERALS for c in text if ord(c) >= 128)
for path in sorted((root / 'src').rglob('*')):
    # The boot page has its own Flash glyphs because SD may be absent. The
    # provisioning page is a served web asset, not device UI text, so its
    # embedded HTML must not pull browser-only characters into the fixed subset.
    if path.suffix not in ('.h', '.cpp') or path == target or \
            path.name in ('FirstBootPage.cpp', 'WifiPortalPage.cpp'):
        continue
    source = path.read_text(encoding='utf-8')
    # Comments may conservatively add codepoints, but never remove UI literals.
    for value in re.findall(r'"(?:[^"\\]|\\.)*"', source):
        points.update(ord(c) for c in value if ord(c) >= 128)
points.update((0xFFFD, 0x25A1))
assert len(points) * 76 <= 65536, 'UI font cache would exceed its 64 KiB budget'
values = sorted(points)
lines = [', '.join(f'0x{cp:X}' for cp in values[i:i+12]) for i in range(0, len(values), 12)]
text = ('// Generated by tools/ui_sd_font_preview/prepare_codepoints.py; no glyph pixels.\n'
        '#pragma once\n#include <stdint.h>\n\n'
        'namespace UiFontCodepoints {\ninline constexpr uint32_t kValues[] = {\n  ' +
        ',\n  '.join(lines) + '\n};\n}\n')
if args.check:
    if not target.is_file() or target.read_text(encoding='utf-8') != text:
        raise SystemExit('UI codepoints changed. Run: python tools/ui_sd_font_preview/prepare_codepoints.py')
else:
    target.write_text(text, encoding='utf-8')
print(f'UI font: {len(values)} codepoints, {len(values) * 76} bytes bounded PSRAM cache')
