enum { ESP_QRCODE_ECC_LOW, ESP_QRCODE_ECC_MED, ESP_QRCODE_ECC_QUART, ESP_QRCODE_ECC_HIGH };

typedef struct {
  void (*display_func)(esp_qrcode_handle_t qrcode);
  int max_qrcode_version;
  int qrcode_ecc_level;
} esp_qrcode_config_t;

