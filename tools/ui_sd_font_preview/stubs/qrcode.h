inline esp_err_t esp_qrcode_generate(esp_qrcode_config_t* config, const char* text) {
  if (config == nullptr || config->display_func == nullptr || text == nullptr ||
      strcmp(text, "WIFI:T:nopass;S:OpenBread-Setup-1A2B;;") != 0) {
    return ESP_FAIL;
  }
  config->display_func(uiPreviewWifiQr());
  return ESP_OK;
}

inline int esp_qrcode_get_size(esp_qrcode_handle_t qrcode) { return qrcode[0]; }

inline bool esp_qrcode_get_module(esp_qrcode_handle_t qrcode, int x, int y) {
  const int size = esp_qrcode_get_size(qrcode);
  if (x < 0 || y < 0 || x >= size || y >= size) return false;
  const int rowBytes = (size + 7) / 8;
  return (qrcode[1 + y * rowBytes + x / 8] & (0x80U >> (x & 7))) != 0;
}
